import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterAll, describe, expect, it } from 'vitest';
import {
  OWNER_EMAIL,
  OWNER_NAME,
  OWNER_NOREPLY,
  SESSION_DOMAINS,
  VENDOR_WORDS,
  checkAttribution,
  formatViolations,
  parseIdent,
  readRange,
  stripComments,
} from '../check-attribution.mjs';

const script = fileURLToPath(new URL('../check-attribution.mjs', import.meta.url));
const owner = {
  authorName: OWNER_NAME,
  authorEmail: OWNER_EMAIL,
  committerName: OWNER_NAME,
  committerEmail: OWNER_EMAIL,
};
const sha = 'a'.repeat(40);
// Forbidden names come from the script itself, so this file never spells them out either.
const [vendorA = '', vendorB = ''] = VENDOR_WORDS;
const commit = (message: string, extra = {}) => ({ sha, message, ...owner, ...extra });
const rules = (input: Parameters<typeof checkAttribution>[0]) => checkAttribution(input).map((v) => v.rule);

describe('checkAttribution', () => {
  it('passes a clean history from either owner address', () => {
    const noreply = { authorEmail: OWNER_NOREPLY, committerEmail: OWNER_NOREPLY };
    const commits = [
      commit('feat(fonts): switch the sans\n\nSession storage is never used.'),
      commit('fix(session): keep share links opt-in', noreply),
      commit('docs: fonts.generated.css lists the fallbacks'),
    ];
    expect(checkAttribution({ commits, prTitle: 'Foundations', prBody: 'Adds the trust pages.' })).toEqual(
      [],
    );
  });

  it.each([
    ['co-author trailer', 'Co-authored-by: Someone <someone@example.com>'],
    ['session trailer', `${vendorB}-Session: abc123`],
    ['session trailer', 'Session-Url: https://example.com/s/1'],
    ['generated-by line', 'Generated with a helper'],
    ['generated-by line', 'generated by a helper'],
    ['vendor or model name', `Written using ${vendorA}`],
    ['vendor or model name', `Tuned with ${['g', 'pt'].join('')}-5`],
    ['vendor noreply address', `Signed-off-by: Bot <noreply@${vendorA}.com>`],
    ['session link', `See https://${SESSION_DOMAINS[0]}/code/123`],
  ])('fails on a %s', (rule, line) => {
    const violations = checkAttribution({ commits: [commit(`feat: change\n\n${line}`)] });
    expect(violations.map((v) => v.rule)).toContain(rule);
    expect(formatViolations(violations)).toMatch(
      new RegExp(`^${sha.slice(0, 12)}: ${rule} \\(.+\\)\\. Fix: .+`, 'm'),
    );
  });

  it('fails on a wrong author or committer', () => {
    expect(rules({ commits: [commit('feat: x', { authorName: 'Someone Else' })] })).toEqual([
      'unexpected author',
    ]);
    expect(rules({ commits: [commit('feat: x', { committerEmail: 'bot@example.com' })] })).toEqual([
      'unexpected committer',
    ]);
    const [violation] = checkAttribution({ commits: [commit('feat: x', { authorEmail: 'x@example.com' })] });
    expect(violation?.fix).toContain(`${OWNER_NAME} <${OWNER_EMAIL}>`);
  });

  it('fails on a bad PR title or body and names the source', () => {
    const violations = checkAttribution({
      commits: [],
      prTitle: `Change by ${vendorA}`,
      prBody: 'Summary\n\nCo-authored-by: Someone <s@example.com>',
    });
    expect(formatViolations(violations).split('\n')).toEqual([
      expect.stringMatching(/^PR title: vendor or model name/),
      expect.stringMatching(/^PR body: co-author trailer/),
    ]);
  });
});

describe('message and identity parsing', () => {
  it('reads git identities and ignores the editor comments', () => {
    expect(parseIdent(`${OWNER_NAME} <${OWNER_EMAIL}> 1700000000 +0530`)).toEqual({
      name: OWNER_NAME,
      email: OWNER_EMAIL,
    });
    const message =
      'feat: x\n# Co-authored-by: hint\n# ------------------------ >8 ------------------------\ndiff';
    expect(stripComments(message)).toBe('feat: x');
  });
});

describe('command line', () => {
  const dir = mkdtempSync(join(tmpdir(), 'attribution-'));
  afterAll(() => rmSync(dir, { recursive: true, force: true }));
  const git = (...args: string[]) =>
    execFileSync('git', ['-c', `user.name=${OWNER_NAME}`, '-c', `user.email=${OWNER_EMAIL}`, ...args], {
      cwd: dir,
      encoding: 'utf8',
    }).trim();

  it('rejects a message file with an exit code and a fix', () => {
    const file = join(dir, 'COMMIT_EDITMSG');
    writeFileSync(file, 'feat: x\n\nCo-authored-by: Someone <s@example.com>\n');
    const ident = `${OWNER_NAME} <${OWNER_EMAIL}> 1700000000 +0530`;
    const run = spawnSync(
      process.execPath,
      [script, '--message-file', file, '--author', ident, '--committer', ident],
      { encoding: 'utf8' },
    );
    expect(run.status).toBe(1);
    expect(run.stderr).toContain('commit message: co-author trailer');
    expect(run.stderr).toContain('Fix: Delete the Co-authored-by line.');
  });

  it('reads a commit range with author and committer fields', () => {
    git('init', '-q');
    git('commit', '-q', '--allow-empty', '-m', 'chore: base');
    const base = git('rev-parse', 'HEAD');
    git('commit', '-q', '--allow-empty', '-m', 'feat: one\n\nBody line.');
    git('commit', '-q', '--allow-empty', '-m', 'feat: two\n\nCo-authored-by: X <x@example.com>');
    const head = git('rev-parse', 'HEAD');
    const commits = readRange(base, head, dir);
    expect(commits.map((c) => c.message.split('\n')[0])).toEqual(['feat: two', 'feat: one']);
    expect(commits[0]).toMatchObject({ ...owner, sha: head });
    expect(rules({ commits })).toEqual(['co-author trailer']);
    expect(() => readRange('--output=x', head, dir)).toThrow('full commit SHA');
  });
});

describe('forbidden words', () => {
  it('appear in neither the script nor this test as plain text', () => {
    for (const file of [script, fileURLToPath(import.meta.url)]) {
      const source = readFileSync(file, 'utf8').toLowerCase();
      for (const word of [...VENDOR_WORDS, ...SESSION_DOMAINS]) expect(source).not.toContain(word);
    }
  });
});
